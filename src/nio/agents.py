"""Agent cards: load the shipped, personal and team cards, resolve tier and effort through config, and render
them as each host's native subagent files. Verify that Claude ran each one on the model its tier maps to."""
import json
import os
import re
import shutil
from importlib import resources
from pathlib import Path

from nio import records

ORDER = ["cheap", "strong", "max", "frontier"]  # ascending; a host with no model for a tier uses the nearest lower one
TIERS = set(ORDER)
EFFORT = {"low": "low", "med": "medium", "high": "high"}
TOOLS = {"read": ["Read", "Grep", "Glob"], "edit": ["Edit", "Write"], "shell": ["Bash"], "web": ["WebSearch", "WebFetch"]}
FIELDS = {"name", "description", "tier", "effort", "tools", "hosts"}
SECTIONS = ["Job", "Inputs", "Output format", "Stop when"]
# Claude aliases resolve to the newest model; Codex names change too often to guess
DEFAULT_TIERS = {"claude": {"cheap": "haiku", "strong": "sonnet", "max": "opus", "frontier": "fable"}}
MARK = "generated by `nio agents sync`; edit the card, not this file"
OUT = {"claude": (".claude/agents", ".md"), "codex": (".codex/agents", ".toml")}


def layers(root):
    """Card folders, lowest priority first: shipped, personal, team."""
    return [Path(str(resources.files("nio").joinpath("agents"))), records.home() / "agents", root / ".nio/agents"]


def load(root):
    """Return {name: (meta, body, source path)}. A same-name card replaces a lower layer's; <name>.append.md adds to it."""
    cards, appends = {}, {}
    for folder in layers(root):
        for path in sorted(folder.glob("*.md")) if folder.is_dir() else []:
            if path.name.endswith(".append.md"):
                appends.setdefault(path.name[: -len(".append.md")], []).append(path.read_text().strip())
                continue
            try:
                meta, body = records.parse(path)
            except Exception as e:
                raise ValueError(f"{path}: {e}") from e
            cards[meta.get("name") or path.stem] = (meta, "\n".join(body).strip(), path)
    for name, extra in appends.items():
        if name not in cards:
            raise ValueError(f"{name}.append.md: no card named `{name}` to append to")
        meta, body, path = cards[name]
        cards[name] = (meta, "\n\n".join([body, *extra]), path)
    return cards


def check(name, meta, body):
    errs = [f"unknown field `{k}`" for k in meta if k not in FIELDS]
    errs += [f"missing `{k}`" for k in ("name", "description", "tier", "effort") if not meta.get(k)]
    if meta.get("tier") and meta["tier"] not in TIERS | {"all"}:
        errs.append(f"`tier` must be one of {sorted(TIERS)} or all")
    if meta.get("effort") and meta["effort"] not in EFFORT:
        errs.append(f"`effort` must be one of {sorted(EFFORT)}")
    errs += [f"unknown tool `{t}`, use {sorted(TOOLS)}" for t in meta.get("tools") or [] if t not in TOOLS]
    secs = records.sections(body.splitlines())
    errs += [f"section `## {s}` is missing or empty" for s in SECTIONS if not secs.get(s)]
    for host, extra in (meta.get("hosts") or {}).items():
        if host not in OUT or not isinstance(extra, dict):
            errs.append(f"`hosts` keys must be {sorted(OUT)}, each a mapping")
        elif any(isinstance(v, (dict, list)) for v in extra.values()):
            errs.append(f"`hosts.{host}` values must be plain strings, numbers or booleans")
    if not re.fullmatch(r"[a-z0-9-]+", name):
        errs.append("name must be lowercase letters, digits and dashes")
    return errs


def hosts(cfg):
    """Configured hosts, else the ones whose CLI is installed. Returns (hosts, picked automatically)."""
    listed = cfg.get("agents", {}).get("hosts")
    if listed:
        return [h for h in listed if h in OUT], False
    return [h for h in OUT if shutil.which(h)], True


def resolve(cfg, name, meta, host):
    """(tier, model or None, effort, warning) for a card on a host, after config overrides; `name` None for a task's
    worker, which has no card to override. A tier the host maps no model to falls to the nearest lower one it maps
    (#42 FR-52); the warning says so, or that the parent's model is inherited when no lower tier is mapped either."""
    agents = cfg.get("agents", {})
    over = agents.get("override", {}).get(name, {}) if name else {}
    tier, effort = over.get("tier", meta["tier"]), over.get("effort", meta["effort"])
    models = records.merge(DEFAULT_TIERS, agents.get("tiers", {})).get(host, {})
    lower = next((t for t in reversed(ORDER[:ORDER.index(tier) + 1]) if models.get(t)), None)
    model = models.get(lower)
    warning = "" if lower == tier else (f"no model for tier `{tier}`; using `{lower}` ({model})" if lower
                                         else f"no model for tier `{tier}` or below; the parent's model is inherited")
    return tier, model, EFFORT[effort], warning


def render_claude(name, meta, body, model, effort):
    head = {"name": f"nio-{name}", "description": meta["description"]}
    if model:
        head["model"] = model
    head["effort"] = effort
    if meta.get("tools"):
        head["tools"] = ", ".join(t for k in meta["tools"] for t in TOOLS[k])
    head.update((meta.get("hosts") or {}).get("claude", {}))
    lines = [f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in head.items()]  # JSON scalars are valid YAML
    return "---\n" + "\n".join(lines) + f"\n---\n<!-- {MARK} -->\n\n{body}\n"


def render_codex(name, meta, body, model, effort):
    head = {"name": f"nio-{name}", "description": meta["description"], "developer_instructions": body}
    if model:
        head["model"] = model
    head["model_reasoning_effort"] = effort
    head.update((meta.get("hosts") or {}).get("codex", {}))
    lines = [f"{k} = {json.dumps(v, ensure_ascii=False)}" for k, v in head.items()]  # JSON strings, numbers and bools are valid TOML;
    # ensure_ascii=False because TOML rejects the surrogate pairs JSON uses for emoji
    if "shell" not in (meta.get("tools") or []):
        lines += ["", "[features]", "shell_tool = false"]
    return f"# {MARK}\n" + "\n".join(lines) + "\n"


RENDER = {"claude": render_claude, "codex": render_codex}


def exclude(root):
    """Keep rendered files out of git without a committed .gitignore change."""
    path = root / records.git(root, "rev-parse", "--git-path", "info/exclude")[0]
    have = path.read_text().splitlines() if path.exists() else []
    want = [f"{folder}/nio-*" for folder, _ in OUT.values()]
    if missing := [w for w in want if w not in have]:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(have + missing) + "\n")


def sync(root):
    """Render every card for every host. Returns (lines to print, errors)."""
    cfg = records.config(root)
    cards = load(root)
    errors = [f"{p}: {e}" for n, (m, b, p) in cards.items() for e in check(n, m, b)]
    if errors:
        return [], errors
    picked, auto = hosts(cfg)
    out = [f"hosts: {', '.join(picked) or 'none'}" + (" (CLIs on PATH; set agents.hosts in config to choose)" if auto else "")]
    if os.environ.get("CLAUDE_CODE_SUBAGENT_MODEL") and "claude" in picked:
        out.append(f"WARN  CLAUDE_CODE_SUBAGENT_MODEL={os.environ['CLAUDE_CODE_SUBAGENT_MODEL']} overrides every agent's model on Claude")
    for host in picked:
        folder, ext = OUT[host]
        target = root / folder
        target.mkdir(parents=True, exist_ok=True)
        wanted = set()
        # a `tier: all` card (the task worker) renders once per tier as nio-<name>-<tier>, with no override (CT-15, FR-6)
        each = [(f"{n}-{t}", n, {**m, "tier": t}, b) if m["tier"] == "all" else (n, n, m, b)
                for n, (m, b, _) in sorted(cards.items()) for t in (ORDER if m["tier"] == "all" else [None])]
        for name, card, meta, body in each:
            tier, model, effort, warning = resolve(cfg, card if card == name else None, meta, host)
            if warning:
                out.append(f"WARN  {host}: nio-{name}: {warning} (set agents.tiers.{host})")
            path = target / f"nio-{name}{ext}"
            wanted.add(path)
            text = RENDER[host](name, meta, body, model, effort)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                out.append(f"wrote {path.relative_to(root)}  ({model or 'inherit'}, {effort})")
        for stale in target.glob(f"nio-*{ext}"):
            if stale not in wanted and MARK in stale.read_text():
                stale.unlink()
                out.append(f"removed {stale.relative_to(root)}")
    if "codex" in picked:
        out.append("NOTE  codex: an agent can only lose the shell; `read`-only cards are read-only by instruction there")
    exclude(root)
    return out, []


def replies(log):
    """The assistant entries of a transcript; a run still being written may end in a partial line."""
    out = []
    for line in log.read_text().splitlines() if log.exists() else []:
        try:
            entry = json.loads(line)
        except json.JSONDecodeError:
            continue
        if entry.get("type") == "assistant":
            out.append(entry)
    return out


def verify(root, limit=20):
    """Compare the model each recent Claude run of a nio-* agent used with the one its tier maps to now."""
    cfg = records.config(root)
    cards = load(root)
    claude = Path(os.environ.get("CLAUDE_CONFIG_DIR") or Path.home() / ".claude")
    project = claude / "projects" / re.sub(r"[^A-Za-z0-9]", "-", str(root))
    runs = sorted(project.glob("*/subagents/*.meta.json"), key=lambda p: p.stat().st_mtime, reverse=True)
    out, bad = [], 0
    for meta_path in runs:
        kind = json.loads(meta_path.read_text()).get("agentType", "")
        name = kind.removeprefix("nio-")
        if not kind.startswith("nio-") or name not in cards:
            continue
        _, want, _, _ = resolve(cfg, name, cards[name][0], "claude")
        log = meta_path.with_name(meta_path.name.replace(".meta.json", ".jsonl"))
        # only the agent's own replies: other entries (request shapes) carry the parent session's model
        used = sorted({o["message"]["model"] for o in replies(log) if o.get("message", {}).get("model")})
        ok = bool(used) and (not want or all(want in m for m in used))
        bad += not ok
        out.append(f"{'ok  ' if ok else 'MISMATCH'} {kind}: wanted {want or 'inherit'}, ran {', '.join(used) or 'nothing recorded'}  ({log.parent.parent.name[:8]})")
        if len(out) >= limit:
            break
    if not out:
        out.append(f"no runs of nio-* agents found under {project}")
    if "codex" in hosts(cfg)[0]:
        out.append("codex: unverified (its transcript format is not known yet)")
    return out, bad
